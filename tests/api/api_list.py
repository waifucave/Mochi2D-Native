#!/usr/bin/env python3
"""The C API's stability list (docs/api-stability.md), generated from
include/mochi2d.h and the marks of tests/api/marks.txt.

  api_list.py            writes docs/api-stability.md
  api_list.py --check    fails when the committed list is not today's
  api_list.py --exports <shared library> [--nm <nm>] [--dumpbin <dumpbin>]
                         fails unless the library exports exactly the
                         header's functions, and nothing but m2d_ symbols
"""
import fnmatch
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HEADER = os.path.join(ROOT, "include", "mochi2d.h")
MARKS = os.path.join(ROOT, "tests", "api", "marks.txt")
OUT = os.path.join(ROOT, "docs", "api-stability.md")


def header_names():
    """(name, kind) in header order: functions, types and constants."""
    text = open(HEADER, encoding="utf-8").read()
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    found = []
    seen = set()

    def add(name, kind):
        if name not in seen:
            seen.add(name)
            found.append((name, kind))

    pattern = re.compile(
        r"M2D_API\s+[^;(]*?\b(m2d_\w+)\s*\("                      # functions
        r"|typedef\s+struct\s+(m2d_\w+)\s+(m2d_\w+)\s*;"          # opaque handles
        r"|typedef\s+(?:struct|enum)\s+(m2d_\w+)\s*\{"            # structs and enums
        r"|typedef\s+[^;()]*\(\s*\*\s*(m2d_\w+)\s*\)"             # callbacks
        r"|#define\s+(M2D_\w+)"                                   # macros
        r"|\b(M2D_[A-Z0-9_]+)\s*(?==|,|\n\s*\})"                  # enumerators
    )
    for m in pattern.finditer(text):
        if m.group(1):
            add(m.group(1), "function")
        elif m.group(2):
            add(m.group(3), "type")
        elif m.group(4):
            add(m.group(4), "type")
        elif m.group(5):
            add(m.group(5), "type")
        elif m.group(6):
            if m.group(6) in ("M2D_API",):
                continue
            add(m.group(6), "constant")
        elif m.group(7):
            add(m.group(7), "constant")
    return found


def rules():
    out = []
    for line in open(MARKS, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        pattern, mark = line.split()
        if mark not in ("stable", "experimental", "deprecated"):
            sys.exit(f"api-list: {MARKS}: unknown mark {mark!r}")
        out.append((pattern, mark))
    return out


def mark_of(name, marks):
    for pattern, mark in marks:
        if fnmatch.fnmatchcase(name, pattern):
            return mark
    sys.exit(f"api-list: no mark for {name} (add a rule to tests/api/marks.txt)")


def document():
    names = header_names()
    marks = rules()
    rows = [(n, k, mark_of(n, marks)) for n, k in names]
    counts = {}
    for _, k, m in rows:
        counts[(k, m)] = counts.get((k, m), 0) + 1
    lines = [
        "# C API stability",
        "",
        "Every function, type and constant of `include/mochi2d.h`, each with a",
        "stability mark for 1.0. Generated by `tests/api/api_list.py` from the",
        "header and the rules of `tests/api/marks.txt`; the `api-list` test fails",
        "when the header changes without this list. Do not edit by hand.",
        "",
        "| Mark | Meaning |",
        "| --- | --- |",
        "| stable | Part of the 1.0 API: from 1.0 on, it changes incompatibly only in a new major version. |",
        "| experimental | Usable, but may still change in a minor version (always noted in the release notes). |",
        "| deprecated | An old name kept for one release; it goes in 1.0. |",
        "",
        "What is experimental, and why (the rules' comments say more):",
        "",
        "- **The GPU layer:** the frame plan, the programs' sources, and the GL,",
        "  Vulkan, Metal and Direct3D 11 backends, the newest parts; Metal and",
        "  Direct3D 11 have run only on the Apple Paravirtual device and WARP.",
        "- **Live motion sync:** Mochi2D's own analysis, its live input, voice",
        "  calibration and profiles, and the animator's motion sync, as Mochi2D",
        "  marks them. Reading `.motionsync3.json` files is stable.",
        "",
        "| | stable | experimental | deprecated |",
        "| --- | ---: | ---: | ---: |",
    ]
    for k in ("function", "type", "constant"):
        lines.append(f"| {k}s | {counts.get((k, 'stable'), 0)} | {counts.get((k, 'experimental'), 0)} | "
                     f"{counts.get((k, 'deprecated'), 0)} |")
    for title, kind in (("Functions", "function"), ("Types", "type"), ("Constants", "constant")):
        lines += ["", f"## {title}", "", "| Name | Mark |", "| --- | --- |"]
        lines += [f"| `{n}` | {m} |" for n, k, m in rows if k == kind]
    return "\n".join(lines) + "\n"


def exported(lib, nm, dumpbin):
    if lib.lower().endswith(".dll"):
        out = subprocess.run([dumpbin or "dumpbin", "/exports", lib], capture_output=True, text=True, check=True).stdout
        names, table = [], False
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 4 and parts[0] == "ordinal" and parts[1] == "hint":
                table = True
                continue
            if table:
                if not parts:
                    if names:
                        break
                    continue
                if len(parts) >= 4 and parts[0].isdigit():
                    names.append(parts[3])
        return names
    if sys.platform == "darwin":
        out = subprocess.run([nm or "nm", "-gU", lib], capture_output=True, text=True, check=True).stdout
        return [l.split()[-1][1:] for l in out.splitlines() if l.strip() and l.split()[-1].startswith("_")]
    out = subprocess.run([nm or "nm", "-D", "--defined-only", lib], capture_output=True, text=True, check=True).stdout
    return [l.split()[-1] for l in out.splitlines() if l.strip()]


def main(argv):
    if len(argv) > 1 and argv[1] == "--check":
        today = document()
        committed = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if committed != today:
            print("api-list: docs/api-stability.md is not today's: run tests/api/api_list.py", file=sys.stderr)
            a, b = set(committed.splitlines()), set(today.splitlines())
            for line in sorted(b - a)[:20]:
                print(f"  + {line}", file=sys.stderr)
            for line in sorted(a - b)[:20]:
                print(f"  - {line}", file=sys.stderr)
            return 1
        print(f"api-list: {len(header_names())} names, the committed list is today's")
        return 0
    if len(argv) > 2 and argv[1] == "--exports":
        lib = argv[2]
        nm = argv[argv.index("--nm") + 1] if "--nm" in argv else None
        dumpbin = argv[argv.index("--dumpbin") + 1] if "--dumpbin" in argv else None
        names = exported(lib, nm, dumpbin)
        functions = {n for n, k in header_names() if k == "function"}
        stray = sorted(n for n in names if not n.startswith("m2d_"))
        missing = sorted(functions - set(names))
        extra = sorted(set(names) - functions - set(stray))
        for n in stray[:20]:
            print(f"api-exports: not an m2d_ symbol: {n}", file=sys.stderr)
        for n in missing[:20]:
            print(f"api-exports: not exported: {n}", file=sys.stderr)
        for n in extra[:20]:
            print(f"api-exports: exported, not in the header: {n}", file=sys.stderr)
        if stray or missing or extra:
            return 1
        print(f"api-exports: {os.path.basename(lib)} exports the header's {len(functions)} functions, nothing else")
        return 0
    open(OUT, "w", encoding="utf-8", newline="\n").write(document())
    print(f"api-list: wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
