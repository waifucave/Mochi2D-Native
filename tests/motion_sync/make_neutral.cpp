// Regenerates src/framework/motion_sync_neutral.cpp: the neutral voice
// profile that Mochi2D's neutralVoiceProfile() builds, from this project's
// test port of its vowel synthesizer and the library's VoiceCalibration.
//
// usage: mochi2d_make_neutral > src/framework/motion_sync_neutral.cpp
//        mochi2d_make_neutral --json   (the profile as Mochi2D's JSON, for the cross-check)
// (tests/motion_sync/README.md; the unit tests check the committed table
// against this, and the cross-check against Mochi2D's own profile).
#include <cstdio>
#include <cstring>

#include "framework/motion_sync_analysis.hpp"
#include "support/motion_sync_support.hpp"

using namespace mochi2d;
using namespace mochi2d::framework;

int main(int argc, char** argv) {
  const VoiceProfile p = test::build_neutral_profile();
  if (argc > 1 && std::strcmp(argv[1], "--json") == 0) {
    const String json = voice_profile_to_json(p);
    std::fwrite(json.data(), 1, json.size(), stdout);
    return 0;
  }
  std::printf(
      "// Generated by tests/motion_sync/make_neutral.cpp: do not edit.\n"
      "//\n"
      "// The neutral voice profile of Mochi2D's motion-sync analysis\n"
      "// (neutralVoiceProfile in src/anim/motion-sync/analysis.ts): the\n"
      "// calibration of a synthetic voice in four sizes (pitch 105, 150, 205 and\n"
      "// 270 Hz, formants scaled by 0.97, 1.06, 1.16 and 1.26), each vowel 0.6 s.\n"
      "// The values are exact (hexadecimal floating-point literals).\n"
      "#include \"framework/motion_sync_analysis.hpp\"\n\n"
      "namespace mochi2d::framework {\n\n"
      "namespace {\n\n");
  std::printf("constexpr int kNeutralVowels = %d;\n", static_cast<int>(p.templates.size()));
  std::printf("/** The vowels in the profile's order (0 A … 4 O). */\nconstexpr int kNeutralOrder[kNeutralVowels] = {");
  for (std::size_t v = 0; v < p.templates.size(); v++) std::printf("%s%d", v ? ", " : "", p.templates[v].vowel);
  std::printf("};\n");
  std::size_t per = p.templates.empty() ? 0 : p.templates[0].templates.size();
  for (const auto& v : p.templates)
    if (v.templates.size() != per) {
      std::fprintf(stderr, "make_neutral: vowels with different template counts\n");
      return 1;
    }
  std::printf("constexpr int kNeutralPerVowel = %zu;\n", per);
  std::printf("constexpr double kNeutralTemplates[kNeutralVowels][kNeutralPerVowel][kMelBands] = {\n");
  for (const auto& v : p.templates) {
    std::printf("    {\n");
    for (const auto& t : v.templates) {
      std::printf("        {");
      for (int m = 0; m < kMelBands; m++) std::printf("%s%a", m ? ", " : "", t[m]);
      std::printf("},\n");
    }
    std::printf("    },\n");
  }
  std::printf("};\n\n}  // namespace\n\n");
  std::printf(
      "VoiceProfile neutral_voice_profile() {\n"
      "  VoiceProfile p;\n"
      "  p.name = \"neutral synthetic voice\";\n"
      "  for (int v = 0; v < kNeutralVowels; v++) {\n"
      "    VoiceProfile::Vowel entry;\n"
      "    entry.vowel = kNeutralOrder[v];\n"
      "    for (int t = 0; t < kNeutralPerVowel; t++) {\n"
      "      Spectrum s{};\n"
      "      for (int m = 0; m < kMelBands; m++) s[static_cast<std::size_t>(m)] = kNeutralTemplates[v][t][m];\n"
      "      entry.templates.push_back(s);\n"
      "    }\n"
      "    p.templates.push_back(std::move(entry));\n"
      "  }\n"
      "  p.voiced_level = -26;\n"
      "  return p;\n"
      "}\n\n"
      "}  // namespace mochi2d::framework\n");
  return 0;
}
