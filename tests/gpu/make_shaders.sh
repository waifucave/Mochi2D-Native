#!/usr/bin/env bash
# Translates the GPU programs for Metal and Direct3D 11: render/shaders.cpp's
# Cross450 dialect (the Vulkan GLSL with y = +1 at row 0) compiled to SPIR-V
# by glslangValidator, then to MSL 2.0 and HLSL (shader model 5.0) by
# SPIRV-Cross. It writes, all committed, so builds need no shader compiler:
#   src/render/gpu/cross_sources.inc   both languages as C++ string literals
#                                      (the Metal backend compiles the MSL
#                                      at run time; m2d_render_shader_source)
#   src/render/gpu/hlsl/<program>.<vert|frag>.hlsl
#                                      the HLSL, which Windows builds compile
#                                      with fxc (the Direct3D 11 backend)
# Rerun it whenever src/render/shaders.cpp changes; the gpu-shaders test
# fails while the committed files are stale.
#
# usage: tests/gpu/make_shaders.sh <build dir> [out dir]
#        (default out: src/render/gpu; the test writes elsewhere)
set -euo pipefail
BUILD="$(cd "${1:?usage: make_shaders.sh <build dir> [out dir]}" && pwd)"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${2:-$ROOT/src/render/gpu}"
command -v glslangValidator >/dev/null || { echo "make_shaders: glslangValidator missing (glslang-tools)" >&2; exit 77; }
command -v spirv-cross >/dev/null || { echo "make_shaders: spirv-cross missing (spirv-cross)" >&2; exit 77; }
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
"$BUILD/tests/mochi2d-shader-sources" "$TMP" --cross
mkdir -p "$OUT/hlsl"
GLSLANG="$(glslangValidator --version | head -1 | sed 's/^Glslang Version: //')"
CROSS="$(spirv-cross --revision 2>&1 | head -1)"
if [ "$CROSS" = "(Debian package)" ] && command -v dpkg-query >/dev/null; then
  CROSS="$(dpkg-query -W -f '${Version}' spirv-cross)"
fi
HEADER="Generated by tests/gpu/make_shaders.sh from render/shaders.cpp's Cross450 dialect (glslang $GLSLANG, SPIRV-Cross $CROSS). Do not edit."
# A text as C++ string literals, a line each (MSVC limits one literal, not their concatenation).
literal() {
  sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^/  "/' -e 's/$/\\n"/' "$1"
}
{
  echo "// $HEADER"
  for program in mesh mesh_advanced layer layer_advanced mask; do
    for stage in vert frag; do
      glslangValidator -V --target-env vulkan1.0 -o "$TMP/$program.$stage.spv" "$TMP/$program.$stage" >"$TMP/log" ||
        { cat "$TMP/log" >&2; exit 1; }
      spirv-cross "$TMP/$program.$stage.spv" --msl --msl-version 20000 --msl-decoration-binding \
        --rename-entry-point main "m2d_${program}_${stage}" "$stage" --output "$TMP/$program.$stage.metal"
      spirv-cross "$TMP/$program.$stage.spv" --hlsl --shader-model 50 --output "$TMP/$program.$stage.hlsl"
      { echo "// $HEADER"; cat "$TMP/$program.$stage.hlsl"; } >"$OUT/hlsl/$program.$stage.hlsl"
      echo "const char kMsl_${program}_${stage}[] ="
      literal "$TMP/$program.$stage.metal"
      echo "  ;"
      echo "const char kHlsl_${program}_${stage}[] ="
      literal "$TMP/$program.$stage.hlsl"
      echo "  ;"
    done
  done
} >"$OUT/cross_sources.inc.tmp"
mv "$OUT/cross_sources.inc.tmp" "$OUT/cross_sources.inc"
echo "make_shaders: wrote $OUT/cross_sources.inc and $OUT/hlsl/"
