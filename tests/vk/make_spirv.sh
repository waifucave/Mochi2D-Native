#!/usr/bin/env bash
# Compiles the GPU programs' Vulkan GLSL (made from the GL backend's text by
# render/shaders.cpp) to SPIR-V with glslangValidator, and writes the words
# as C++ arrays: src/render/vk/spirv.inc, which is committed, so builds need
# no shader compiler. Rerun it whenever src/render/shaders.cpp changes; the
# vk-spirv test fails while the committed file is stale.
#
# usage: tests/vk/make_spirv.sh <build dir> [out file]
#        (default out: src/render/vk/spirv.inc; the test writes elsewhere)
set -euo pipefail
BUILD="$(cd "${1:?usage: make_spirv.sh <build dir> [out file]}" && pwd)"
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${2:-$ROOT/src/render/vk/spirv.inc}"
command -v glslangValidator >/dev/null || { echo "make_spirv: glslangValidator missing (glslang-tools)" >&2; exit 77; }
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
"$BUILD/tests/mochi2d-shader-sources" "$TMP"
{
  echo "// Generated by tests/vk/make_spirv.sh from render/shaders.cpp's Vulkan dialect"
  echo "// ($(glslangValidator --version | head -1 | sed 's/^Glslang Version: //'), --target-env vulkan1.0). Do not edit."
  for program in mesh mesh_advanced layer layer_advanced mask; do
    for stage in vert frag; do
      glslangValidator -V --target-env vulkan1.0 -o "$TMP/$program.$stage.spv" "$TMP/$program.$stage" >"$TMP/log" ||
        { cat "$TMP/log" >&2; exit 1; }
      if command -v spirv-val >/dev/null; then spirv-val --target-env vulkan1.0 "$TMP/$program.$stage.spv"; fi
      echo "const uint32_t kSpirv_${program}_${stage}[] = {"
      od -An -v -t x4 "$TMP/$program.$stage.spv" | awk '{ line = " "; for (i = 1; i <= NF; i++) line = line " 0x" $i ","; print line }'
      echo "};"
    done
  done
} >"$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "make_spirv: wrote $OUT"
